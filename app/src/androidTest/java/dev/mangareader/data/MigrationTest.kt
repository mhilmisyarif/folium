package dev.mangareader.data

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Upgrading keeps users' data (spec §11): a database as the first Room release (v1) created it is migrated to the
 * current version. Room validates every table against the entities after migrating, so a schema mismatch fails here.
 * No schemas were exported for old versions, so v1 is today's SQL (generated by Room) minus what v2–v4 added.
 */
@RunWith(AndroidJUnit4::class)
class MigrationTest {
    private val context: Context = ApplicationProvider.getApplicationContext()
    private val name = "migration-test.db"

    @Before @After fun clean() {
        context.deleteDatabase(name)
    }

    @Test fun v1_to_latest_keepsLibraryData() {
        createV1()
        val db = Room.databaseBuilder(context, AppDatabase::class.java, name)
            .addMigrations(AppDatabase.MIGRATION_1_2, AppDatabase.MIGRATION_2_3, AppDatabase.MIGRATION_3_4)
            .allowMainThreadQueries()
            .build()
        try {
            val dao = db.dao()
            runBlocking {
                val manga = dao.manga("SRC:/m/1")!!
                assertEquals("Judul Lama", manga.title)
                assertNull(manga.publicUrl) // v2 column, empty for old rows

                val history = dao.history("SRC:/m/1")!!
                assertEquals("/c/2", history.chapterUrl)
                assertEquals(7, history.page)
                assertEquals(0f, history.offset) // v4 column default

                assertEquals(listOf(1L), dao.favouriteCategoryIds("SRC:/m/1"))
                assertEquals(1, dao.allBookmarks().size)
                assertEquals(2, dao.chapters("SRC:/m/1").size)
                assertNull(dao.status("SRC:/m/1")) // v3 table exists and is empty

                // New features work on the migrated database.
                dao.upsertStatus(LibraryStatusEntity("SRC:/m/1", 1))
                assertEquals(1, dao.status("SRC:/m/1"))
            }
        } finally {
            db.close()
        }
    }

    private fun createV1() {
        val file = context.getDatabasePath(name).apply { parentFile?.mkdirs() }
        SQLiteDatabase.openOrCreateDatabase(file, null).use { db ->
            V1_SCHEMA.forEach(db::execSQL)
            db.execSQL("INSERT INTO manga VALUES ('SRC:/m/1','/m/1','Judul Lama','https://x/c.jpg',NULL,NULL,'Action','SRC')")
            db.execSQL("INSERT INTO chapters VALUES ('SRC:/m/1','/c/2','Bab 2',0), ('SRC:/m/1','/c/1','Bab 1',1)")
            db.execSQL("INSERT INTO favourite_categories (id,title,createdAt,track) VALUES (1,'Favorit',1,1)")
            db.execSQL("INSERT INTO favourites VALUES ('SRC:/m/1',1,2)")
            db.execSQL("INSERT INTO history VALUES ('SRC:/m/1','/c/2','Bab 2',7,0.5,3)")
            db.execSQL("INSERT INTO bookmarks VALUES ('SRC:/m/1','/c/2','Bab 2',3,'https://x/p3.jpg',4)")
            db.execSQL("INSERT INTO downloads VALUES ('SRC:/m/1','/c/1','Bab 1',1,NULL,5)")
            db.version = 1
        }
    }

    private companion object {
        val V1_SCHEMA = listOf(
            "CREATE TABLE IF NOT EXISTS `manga` (`id` TEXT NOT NULL, `url` TEXT NOT NULL, `title` TEXT NOT NULL, `coverUrl` TEXT NOT NULL, `description` TEXT, `author` TEXT, `tags` TEXT NOT NULL, `source` TEXT NOT NULL, PRIMARY KEY(`id`))",
            "CREATE TABLE IF NOT EXISTS `chapters` (`mangaId` TEXT NOT NULL, `url` TEXT NOT NULL, `name` TEXT NOT NULL, `position` INTEGER NOT NULL, PRIMARY KEY(`mangaId`, `url`), FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE TABLE IF NOT EXISTS `favourite_categories` (`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, `title` TEXT NOT NULL, `createdAt` INTEGER NOT NULL, `track` INTEGER NOT NULL)",
            "CREATE TABLE IF NOT EXISTS `favourites` (`mangaId` TEXT NOT NULL, `categoryId` INTEGER NOT NULL, `createdAt` INTEGER NOT NULL, PRIMARY KEY(`mangaId`, `categoryId`), FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE , FOREIGN KEY(`categoryId`) REFERENCES `favourite_categories`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE INDEX IF NOT EXISTS `index_favourites_categoryId` ON `favourites` (`categoryId`)",
            "CREATE TABLE IF NOT EXISTS `history` (`mangaId` TEXT NOT NULL, `chapterUrl` TEXT NOT NULL, `chapterName` TEXT NOT NULL, `page` INTEGER NOT NULL, `percent` REAL NOT NULL, `updatedAt` INTEGER NOT NULL, PRIMARY KEY(`mangaId`), FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE TABLE IF NOT EXISTS `bookmarks` (`mangaId` TEXT NOT NULL, `chapterUrl` TEXT NOT NULL, `chapterName` TEXT NOT NULL, `page` INTEGER NOT NULL, `imageUrl` TEXT NOT NULL, `createdAt` INTEGER NOT NULL, PRIMARY KEY(`mangaId`, `chapterUrl`, `page`), FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE TABLE IF NOT EXISTS `track_logs` (`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, `mangaId` TEXT NOT NULL, `chapters` TEXT NOT NULL, `createdAt` INTEGER NOT NULL, `unread` INTEGER NOT NULL, FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE INDEX IF NOT EXISTS `index_track_logs_mangaId` ON `track_logs` (`mangaId`)",
            "CREATE TABLE IF NOT EXISTS `stats` (`mangaId` TEXT NOT NULL, `startedAt` INTEGER NOT NULL, `durationMs` INTEGER NOT NULL, `pages` INTEGER NOT NULL, PRIMARY KEY(`mangaId`, `startedAt`), FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE TABLE IF NOT EXISTS `scrobblings` (`service` TEXT NOT NULL, `mangaId` TEXT NOT NULL, `targetId` TEXT NOT NULL, `targetTitle` TEXT NOT NULL, `lastChapter` INTEGER NOT NULL, PRIMARY KEY(`service`, `mangaId`), FOREIGN KEY(`mangaId`) REFERENCES `manga`(`id`) ON UPDATE NO ACTION ON DELETE CASCADE )",
            "CREATE TABLE IF NOT EXISTS `downloads` (`mangaId` TEXT NOT NULL, `chapterUrl` TEXT NOT NULL, `chapterName` TEXT NOT NULL, `state` INTEGER NOT NULL, `error` TEXT, `createdAt` INTEGER NOT NULL, PRIMARY KEY(`mangaId`, `chapterUrl`))",
        )
    }
}
